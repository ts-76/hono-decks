import type { CompiledDeck, SlideFrontmatter } from "../../deck/model";
import { normalizeMountPath } from "../../server/paths";
import type { GeneratedModuleDeck } from "../mdx-module-generator";
import { DECKS_ADVANCED_ENTRY, DECKS_RUNTIME_ENTRY } from "../package-entry";

export interface EmitModuleDecksRouterInput {
  decks: GeneratedModuleDeck[];
  /** Public mount path baked into asset URLs. */
  mountPath?: string;
  /** Development live-reload event stream, set only by the Vite dev server. */
  liveReloadPath?: string;
}

/** Emits `generated/decks.ts`: compiled deck data plus the `createDecks()` entry point. */
export function emitModuleDecksRouter(input: EmitModuleDecksRouterInput): string {
  const slideImports = input.decks.flatMap((deck, deckIndex) =>
    deck.slideModules.map(
      (slide, index) => `import ${slideImportName(deckIndex, index)} from ${JSON.stringify(slide.importPath)};`,
    ),
  );
  const componentImports = input.decks.flatMap((deck, deckIndex) =>
    deck.componentModulePath
      ? [`import * as ${componentImportName(deckIndex)} from ${JSON.stringify(deck.componentModulePath)};`]
      : [],
  );
  const advancedImports = ["configureDecks"];
  if (componentImports.length > 0) advancedImports.push("withClientComponentIds");
  const generatedInput = [
    "mountPath",
    "decks: compiledDecks",
    "clientBundle: decksClientEntry",
    ...(input.liveReloadPath ? [`liveReloadPath: ${JSON.stringify(input.liveReloadPath)}`] : []),
  ];

  return `// Generated by hono-decks. Do not edit; run \`hono-decks compile\` instead.
import type { Env } from "hono";
import type { CompiledDeck, ConfiguredDecks, DecksOptions } from ${JSON.stringify(DECKS_RUNTIME_ENTRY)};
import { ${advancedImports.join(", ")} } from ${JSON.stringify(DECKS_ADVANCED_ENTRY)};
import { decksClientEntry } from "./client-entry";
${[...slideImports, ...componentImports].join("\n")}

/** Mount path from hono-decks.config.ts. Asset URLs were compiled against it. */
export const mountPath = ${JSON.stringify(normalizeMountPath(input.mountPath ?? "/decks"))};

export const compiledDecks: CompiledDeck[] = [
${input.decks.map((deck, deckIndex) => emitDeckObject(deck, deckIndex)).join(",\n")}
];

/** Creates the application API: \`app.route(decks.mountPath, decks.router())\`. */
export function createDecks<E extends Env = any>(options?: DecksOptions<E>): ConfiguredDecks<E> {
  return configureDecks<E>({ ${generatedInput.join(", ")} }, options);
}
`;
}

function emitDeckObject(generated: GeneratedModuleDeck, deckIndex: number): string {
  const { deck } = generated;
  const fields: [string, string][] = [
    ["slug", JSON.stringify(deck.slug)],
    ["sourcePath", JSON.stringify(deck.sourcePath)],
    ["kind", JSON.stringify(deck.kind)],
    ["meta", serializeValue(deck.meta, 2)],
  ];
  if (typeof deck.clientEntryRequired === "boolean")
    fields.push(["clientEntryRequired", String(deck.clientEntryRequired)]);
  if (deck.themeStyle) fields.push(["themeStyle", serializeValue(deck.themeStyle, 2)]);
  if (deck.themeSourcePath) fields.push(["themeSourcePath", JSON.stringify(deck.themeSourcePath)]);
  fields.push(["assets", serializeValue(deck.assets, 2)]);
  if (generated.componentModulePath) {
    fields.push([
      "componentRegistry",
      `withClientComponentIds(${componentImportName(deckIndex)}, ${serializeValue(generated.clientComponentIds ?? {}, 2)})`,
    ]);
  }
  fields.push(["warnings", serializeValue(deck.warnings, 2)]);
  fields.push([
    "slides",
    `[\n${deck.slides.map((slide) => emitSlideObject(deck, slide, deckIndex)).join(",\n")}\n    ]`,
  ]);
  return `  {\n${fields.map(([key, value]) => `    ${key}: ${value}`).join(",\n")}\n  }`;
}

function emitSlideObject(deck: CompiledDeck, slide: CompiledDeck["slides"][number], deckIndex: number): string {
  const fields: [string, string][] = [
    ["index", String(slide.index)],
    ["meta", serializeValue(compactSlideMeta(slide.meta, deck), 4)],
  ];
  if (slide.notes !== undefined) fields.push(["notes", serializeValue(slide.notes, 4)]);
  fields.push(["render", slideImportName(deckIndex, slide.index)]);
  return `      {\n${fields.map(([key, value]) => `        ${key}: ${value}`).join(",\n")}\n      }`;
}

/** Drops values the runtime re-derives from the deck (see inheritDeckDefaults) and duplicated notes. */
function compactSlideMeta(
  meta: SlideFrontmatter,
  deck: CompiledDeck,
): Partial<SlideFrontmatter> & { meta: SlideFrontmatter["meta"] } {
  const { notes: _notes, ...rest } = meta;
  const compact: Partial<SlideFrontmatter> & { meta: SlideFrontmatter["meta"] } = { ...rest };
  if (compact.transition === deck.meta.transition) delete compact.transition;
  if (compact.transitionDuration === deck.meta.transitionDuration) delete compact.transitionDuration;
  if (compact.transitionEasing === deck.meta.transitionEasing) delete compact.transitionEasing;
  return compact;
}

function slideImportName(deckIndex: number, slideIndex: number): string {
  return `Slide_${deckIndex}_${slideIndex}`;
}

function componentImportName(deckIndex: number): string {
  return `Components_${deckIndex}`;
}

function serializeValue(value: unknown, depth: number): string {
  const indent = "  ".repeat(depth);
  const nextIndent = "  ".repeat(depth + 1);

  if (value === undefined) return "undefined";
  if (value instanceof Uint8Array) return `new Uint8Array([${[...value].join(", ")}])`;
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((item) => `${nextIndent}${serializeValue(item, depth + 1)}`).join(",\n")}\n${indent}]`;
  }
  if (typeof value === "object" && value !== null) {
    const entries = Object.entries(value).filter(([, item]) => item !== undefined);
    if (entries.length === 0) return "{}";
    return `{\n${entries
      .map(([key, item]) => `${nextIndent}${JSON.stringify(key)}: ${serializeValue(item, depth + 1)}`)
      .join(",\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}
